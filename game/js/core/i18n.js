  var SUPPORTED = [
    { code: 'en', name: 'English' },
    { code: 'es', name: 'Español' },
    { code: 'de', name: 'Deutsch' }
  ];

  var current = 'en';

  return {
    SUPPORTED: SUPPORTED,
    STRINGS: STRINGS,
    get language() { return current; },
    setLanguage: function (code) {
      for (var i = 0; i < SUPPORTED.length; i++) {
        if (SUPPORTED[i].code === code) { current = code; return true; }
      }
      return false;
    },
    /** Translate; falls back to English, then to the key itself. */
    t: function (key) {
      var lang = STRINGS[current];
      if (lang && lang[key] !== undefined) return lang[key];
      if (STRINGS.en[key] !== undefined) return STRINGS.en[key];
      return key;
    },
    /** Every language must define exactly the same key set (tested). */
    keySet: function (code) {
      var o = STRINGS[code] || {};
      return Object.keys(o).sort();
    }
  };
